#!/usr/bin/env python3
"""Package Maps for Runtipi (runtime.package: source).

Run from anywhere after changing the compose shape:  python3 tools/package.py
The App Manager copies the pinned commit to ${APP_SOURCE_DIR}; every container runs from that read-only copy.
Four services share the app-data folder (/data):
  maps          the app: API, MCP, view, saved places, region jobs (stdlib Python)
  maps-search   Photon (search) supervisor: engines/photon.sh in the unmodified Temurin JRE image
  maps-routing  Valhalla (directions) supervisor: engines/engine.py in the unmodified Valhalla image
  maps-transit  MOTIS (transit) supervisor: same image, engines/engine.py motis
Engines are never published: only the app reaches them on the app's own network.
Writes runtipi/docker-compose.yml. Edit here, never by hand.
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PY = 'python:3.14-alpine@sha256:5862d971d1f0ae26b258cefa4e893556b1d3aba81bd2ff30888704ad378bab67'
JRE = 'eclipse-temurin:21-jre@sha256:ca73b4d3961703d6d7830a4361f49ef0478f8f28b39defc07bb72f4cc7f834f6'
VALHALLA = 'ghcr.io/valhalla/valhalla-scripted@sha256:693617873d42f24d9023eaa9aa002dccd832c9629c9ce8b60eb4ff30547215e1'
VOLUMES = ['${APP_SOURCE_DIR}:/app:ro', '${APP_DATA_DIR}/data:/data']
HARDEN = {'user': '1000:1000', 'cap_drop': ['ALL'], 'security_opt': ['no-new-privileges:true'], 'read_only': True,
          'tmpfs': ['/tmp'], 'init': True, 'restart': 'unless-stopped'}


def engine(image, command, mem, cpus, env, entrypoint=None):
    svc = dict(image=image, **HARDEN)
    if entrypoint:
        svc['entrypoint'] = entrypoint
    svc.update({'command': command, 'working_dir': '/data', 'mem_limit': mem, 'cpus': cpus, 'environment': env,
                'volumes': list(VOLUMES), 'depends_on': {'maps': {'condition': 'service_healthy'}}})
    return svc


def main():
    for name in ('app/server.py', 'app/maps.py', 'engines/engine.py', 'engines/photon.sh', 'openapi.json',
                 'web/index.html', 'web/app.js', 'web/dist/maplibre-gl.mjs'):
        assert (ROOT / name).is_file(), name
    app = dict(image=PY, **HARDEN)
    app.update({
        'working_dir': '/app',
        'command': ['python', '/app/app/server.py'],
        'mem_limit': '512m',
        'cpus': 2,
        'environment': {
            'PORT': '8799', 'DATA_DIR': '/data', 'PYTHONDONTWRITEBYTECODE': '1', 'PYTHONUNBUFFERED': '1',
            'PHOTON_URL': 'http://maps-search:2322', 'VALHALLA_URL': 'http://maps-routing:8002',
            'MOTIS_HOST': 'maps-transit',
            'WIZARD_TRUSTED_HOSTS': '${WIZARD_TRUSTED_HOSTS:-}', 'WIZARD_TRUSTED_ORIGINS': '${WIZARD_TRUSTED_ORIGINS:-}',
            # The App Manager may publish on another host port than 8799: the agent gateway calls that loopback port.
            'WIZARD_APP_HOSTS': '127.0.0.1:${APP_PORT},localhost:${APP_PORT}',
        },
        'volumes': list(VOLUMES),
        'healthcheck': {'test': ['CMD', 'python', '-c', "import urllib.request;urllib.request.urlopen('http://127.0.0.1:8799/healthz',timeout=3)"],
                        'interval': '15s', 'timeout': '5s', 'retries': 6},
        'x-runtipi': {'is_main': True, 'internal_port': 8799},
        'ports': ['127.0.0.1:${APP_PORT}:8799'],  # loopback only; the Wizard gateway proxies it
    })
    search = engine(JRE, ['bash', '/app/engines/photon.sh'], '4608m', 3,
                    {'PHOTON_IMPORT_HEAP': '3g', 'PHOTON_SERVE_HEAP': '1g', 'PHOTON_IMPORT_THREADS': '2',
                     'JAVA_TOOL_OPTIONS': '-Djava.io.tmpdir=/tmp'})
    routing = engine(VALHALLA, ['python3', '/app/engines/engine.py', 'valhalla'], '6g', 4,
                     {'ENGINE_THREADS': '4', 'HOME': '/tmp', 'PYTHONDONTWRITEBYTECODE': '1'}, entrypoint=[])
    transit = engine(VALHALLA, ['python3', '/app/engines/engine.py', 'motis'], '4g', 2,
                     {'ENGINE_THREADS': '2', 'HOME': '/tmp', 'PYTHONDONTWRITEBYTECODE': '1'}, entrypoint=[])
    compose = {'services': {'maps': app, 'maps-search': search, 'maps-routing': routing, 'maps-transit': transit},
               'x-runtipi': {'schema_version': 2, 'overrides': []}}
    head = ('# GENERATED by tools/package.py (runtime.package: source). Edit there.\n'
            '# Engines are unmodified upstream images pinned by digest: Eclipse Temurin (GPL-2.0+CE) running Photon\n'
            '# (Apache-2.0), Valhalla (MIT) and MOTIS (MIT); see NOTICE.md.\n')
    (ROOT / 'runtipi/docker-compose.yml').write_text(head + yaml.safe_dump(compose, sort_keys=False, width=100000))
    print('packaged runtipi/docker-compose.yml')


if __name__ == '__main__':
    main()
